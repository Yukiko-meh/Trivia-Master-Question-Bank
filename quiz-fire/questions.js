function hash(s){let h=2166136261;for(let i=0;i<s.length;i++){h^=s.charCodeAt(i);h=Math.imul(h,16777619)}return h>>>0}
function rng(seed){let a=seed;return function(){a|=0;a=a+0x6D2B79F5|0;let t=Math.imul(a^a>>>15,1|a);t=t+Math.imul(t^t>>>7,61|t)^t;return((t^t>>>14)>>>0)/4294967296}}

// 房間代碼格式:年級-題數-隨機碼,例如 g3-10-k7x2
export function parseRoom(room){
  const m=/^(g[1-6]|j[1-3])-(\d{1,2})-([a-z0-9]{3,8})$/.exec(String(room||''));
  if(!m||!DB[m[1]])return null;
  const n=Math.max(1,Math.min(+m[2],DB[m[1]].length));
  return {grade:m[1],n,seed:m[3]};
}
export function pickQuestions(room){
  const r=parseRoom(room);if(!r)return null;
  const rand=rng(hash(room)),a=DB[r.grade].map((q,i)=>i);
  for(let i=a.length-1;i>0;i--){const j=Math.floor(rand()*(i+1));[a[i],a[j]]=[a[j],a[i]]}
  return a.slice(0,r.n).map(i=>({id:i,q:DB[r.grade][i][0],correct:DB[r.grade][i][1],options:DB[r.grade][i].slice(1)}));
}
